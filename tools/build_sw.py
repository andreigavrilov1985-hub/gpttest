"""Generate sw.js with a precache list and a content hash as the cache version.
Run after changing any app file: python3 tools/build_sw.py
"""
import glob
import hashlib
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
files = (['index.html', 'manifest.webmanifest', 'css/style.css']
         + sorted(glob.glob('js/*.js')) + sorted(glob.glob('explainers/*.js')) + sorted(glob.glob('data/*.json'))
         + sorted(glob.glob('fonts/*.woff2')) + sorted(glob.glob('icons/*.png')) + ['icons/icon.svg'])
h = hashlib.sha1()
for f in files:
    h.update(f.encode())
    h.update(open(f, 'rb').read())
version = h.hexdigest()[:10]
assets = ['./'] + files

sw = f"""// Generated by tools/build_sw.py. © 2026 Андрей Г
const CACHE = 'ostrova-{version}';
const ASSETS = {json.dumps(assets, ensure_ascii=False, indent=1)};

self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
}});

self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

// Cache first (works offline after the first visit), network as fallback.
self.addEventListener('fetch', (e) => {{
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== self.location.origin) return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || fetch(e.request).then((res) => {{
    if (res.ok) {{
      const copy = res.clone();
      caches.open(CACHE).then((c) => c.put(e.request, copy));
    }}
    return res;
  }})));
}});
"""
open('sw.js', 'w', encoding='utf-8').write(sw)
print('sw.js', version, len(assets), 'files')
