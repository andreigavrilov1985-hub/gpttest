/** Returns groups that are shorter than the norm: [[group, have, need], ...] */
export function checkPhraseNorms() {
  const short = [];
  for (const [g, need] of Object.entries(MIN)) {
    const have = (PHRASES[g] || []).length;
    if (have < need) short.push([g, have, need]);
  }
  return short;
}

export function totalPhrases() {
  return Object.values(PHRASES).reduce((a, l) => a + l.length, 0);
}
