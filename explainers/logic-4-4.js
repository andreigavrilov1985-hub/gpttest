// Остров 4 · Логика · Тема 4. Комбинаторика по формулам — мини-мультфильм (примеры свои)
import { card, text, emo, kittenActor, at, hid, cap, pop, fade, move, hop, mood, setText, cutLine, draw, episode, beat } from '../js/cartoon-kit.js';

// серия 1: порядок важен или нет
const ep1 = episode({
  title: 'Важен ли порядок',
  terms: ['перестановки n!', 'размещения: порядок важен (n × (n − 1))', 'сочетания: порядок не важен (делим на повторы)', 'правило умножения'],
  svg: `${card('p', '3 человека в очередь: 3 × 2 × 1 = 3! = 6', { w: 320, size: 14 })}${card('a', 'капитан и заместитель из 6: 6 × 5 = 30', { w: 320, size: 14, fill: '#fff3d6', stroke: '#f2c46d' })}
    ${card('c', 'двое дежурных из 6: 6 × 5 ÷ 2 = 15', { w: 320, size: 14, fill: '#e2f8ea', stroke: '#9fdcb9' })}${text('w', 'порядок не важен — пары «Аня-Боря» и «Боря-Аня» одинаковые', { size: 11, color: '#1784a6' })}
    ${card('m', '3 рубашки × 2 брюк × 2 обуви = 12', { w: 300, size: 14, fill: '#eef7fb' })}${kittenActor('cat', 'thinking', 22)}`,
  init: { p: hid(180, 26), a: hid(180, 70), c: hid(180, 114), w: hid(180, 144), m: hid(180, 190), cat: at(320, 200) },
  caption0: 'Первым делом спроси: важен ли порядок?',
  beats: beat(
    pop(300, 'p'), cap(800, 'Расставить всех по порядку — факториал: 3! = 6.'),
    pop(2400, 'a'), cap(2400, 'Должности разные — порядок важен: 6 × 5.'),
    pop(4200, ['c', 'w'], 500), cap(4200, 'Двое одинаковых дежурных — порядок не важен: делим на 2.'),
    pop(6200, 'm'), cap(6200, 'Независимый выбор — перемножаем количества.'), mood(6200, 'cat', 'happy'),
  ),
});

// серия 2: турнир — каждый с каждым
const pos = [[180, 40], [270, 90], [250, 180], [110, 180], [90, 90]];
const lines = [];
for (let i = 0; i < 5; i += 1) for (let j = i + 1; j < 5; j += 1) lines.push([`l${i}${j}`, ...pos[i], ...pos[j]]);
const ep2 = episode({
  title: 'Турнир',
  terms: ['каждый с каждым: n × (n − 1) ÷ 2', 'двузначных чисел: 9 × 10 = 90'],
  svg: `${lines.map(([n, x1, y1, x2, y2]) => cutLine(n, x1, y1, x2, y2, '#2bb3c9')).join('')}${pos.map((_, i) => emo(`p${i}`, '♟️', 26)).join('')}
    ${text('f', '5 игроков: 5 × 4 ÷ 2 = 10 партий', { size: 15, color: '#16774a' })}${text('d', 'двузначные: первая цифра 1–9, вторая 0–9 → 9 × 10 = 90', { size: 11, color: '#6d3ad1' })}${kittenActor('cat', 'excited', 22)}`,
  init: { ...Object.fromEntries(pos.map((p, i) => [`p${i}`, hid(p[0], p[1])])), f: hid(180, 216), d: hid(180, 236), cat: at(320, 4) },
  caption0: '5 шахматистов, каждый играет с каждым.',
  beats: beat(
    pop(200, pos.map((_, i) => `p${i}`), 120), lines.map(([n], k) => [900 + k * 300, 'to', n, { dash: 1 }, 280, 'linear']),
    cap(1000, 'Каждый играет с 4 соперниками: 5 × 4. Но каждая партия посчитана дважды.'), pop(4200, 'f'), cap(4200, 'Делим на 2: 10 партий.'),
    pop(5800, 'd'), mood(5800, 'cat', 'happy'),
  ),
});

ep1.interact = { type: 'tapShow', cat: 'cat', items: { a: { say: 'Капитан и заместитель — разные роли: порядок важен.' }, c: { say: 'Два дежурных одинаковы: «А и Б» = «Б и А».' } } };

export default { topic: 'logic-4-4', kind: 'cartoon', episodes: [ep1, ep2] };
