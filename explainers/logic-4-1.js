// Остров 4 · Логика · Тема 1. Прогрессии — мини-мультфильм (примеры свои)
import { card, text, emo, kittenActor, at, hid, cap, pop, fade, move, hop, mood, setText, episode, beat } from '../js/cartoon-kit.js';

const row = (p, vals, y, color) => vals.map((v, i) => card(`${p}${i}`, String(v), { w: 48, h: 38, size: 16, fill: color })).join('');
const ri = (p, n, y) => Object.fromEntries(Array.from({ length: n }, (_, i) => [`${p}${i}`, hid(40 + i * 56, y)]));
const nm = (p, n) => Array.from({ length: n }, (_, i) => `${p}${i}`);

// серия 1: арифметическая и геометрическая
const ep1 = episode({
  title: 'Две прогрессии',
  terms: ['арифметическая: +d, n-й член a + (n − 1)d', 'геометрическая: ×q (знаменатель)', 'знаменатель может быть дробным или отрицательным'],
  svg: `${row('a', [5, 8, 11, 14, 17], 40, '#fff3d6')}${text('ad', '+3 каждый раз: n-й = 5 + (n − 1) × 3', { size: 13, color: '#b06200' })}
    ${row('g', [3, 6, 12, 24, 48], 120, '#eef7fb')}${text('gd', '×2 каждый раз: знаменатель q = 2', { size: 13, color: '#1784a6' })}
    ${text('o', '64, 32, 16 … q = 1/2 · 1, −3, 9, −27 … q = −3', { size: 12, color: '#6d3ad1' })}${kittenActor('cat', 'thinking', 22)}`,
  init: { ...ri('a', 5, 40), ad: hid(180, 76), ...ri('g', 5, 120), gd: hid(180, 156), o: hid(180, 200), cat: at(320, 200) },
  caption0: 'Арифметическая прогрессия: каждый раз прибавляем одно и то же число.',
  beats: beat(
    pop(300, nm('a', 5), 150), pop(1400, 'ad'), cap(1400, '10-й член: 5 + 9 × 3 = 32 — без выписывания всего ряда.'),
    pop(3400, nm('g', 5), 150), pop(4400, 'gd'), cap(3400, 'Геометрическая: каждый раз умножаем на одно число — знаменатель.'),
    cap(6000, 'Знаменатель бывает дробным и даже отрицательным.'), pop(6000, 'o'), mood(6000, 'cat', 'happy'),
  ),
});

// серия 2: суммы
const ep2 = episode({
  title: 'Суммы прогрессий',
  terms: ['сумма арифметической: (первый + последний) × количество ÷ 2', 'сумма степеней двойки: 1 + 2 + 4 + 8 = 16 − 1', 'принадлежит ли число прогрессии'],
  svg: `${card('s', '3 + 7 + 11 + 15 + 19', { w: 220, size: 17 })}${text('f', '(3 + 19) × 5 ÷ 2 = 55', { size: 18, color: '#16774a' })}
    ${card('p', '1 + 2 + 4 + 8 = 15 = 16 − 1', { w: 240, size: 16, fill: '#eef7fb' })}${text('t', 'следующая степень минус 1', { size: 13, color: '#1784a6' })}
    ${card('m', 'есть ли 40 в ряду 4, 7, 10…? (40 − 4) ÷ 3 = 12 — целое → да', { w: 340, size: 12, fill: '#fff3d6', stroke: '#f2c46d' })}${kittenActor('cat', 'excited', 22)}`,
  init: { s: hid(180, 30), f: hid(180, 66), p: hid(180, 116), t: hid(180, 148), m: hid(180, 200), cat: at(320, 200) },
  caption0: 'Как быстро сложить арифметическую прогрессию?',
  beats: beat(
    pop(300, 's'), cap(1000, 'Первый + последний, умножить на количество и разделить на 2.'), pop(1800, 'f'),
    pop(3400, ['p', 't'], 500), cap(3400, 'Сумма степеней двойки на 1 меньше следующей степени.'),
    pop(5400, 'm'), cap(5400, 'Число в ряду, если до него целое число шагов.'), mood(5400, 'cat', 'happy'),
  ),
});

ep1.interact = { type: 'tapShow', cat: 'cat', items: { a4: { say: '17 = 5 + 4 × 3.' }, g4: { say: '48 = 3 × 2 × 2 × 2 × 2.' } } };

export default { topic: 'logic-4-1', kind: 'cartoon', episodes: [ep1, ep2] };
